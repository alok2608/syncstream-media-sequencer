// TestSyncEndIsAnnounced checks the convenience broadcast fires for real.
func TestSyncEndIsAnnounced(t *testing.T) {
	h := newHarness(t)
	window := h.seedWindow(t, "Window 1", 10)

	// A real (short) timer: the service schedules the announcement off the wall
	// clock, so this test uses a wall-clock-sized duration.
	h.now = time.Now().UTC()
	h.svc.now = func() time.Time { return time.Now().UTC() }
	h.svc.syncLead = 10 * time.Millisecond
	if _, err := h.svc.StartSync(context.Background(), SyncRequest{
		MediaID: window.Playlist[0].Media.ID, DurationSeconds: 1,
	}); err != nil {
		t.Fatalf("start sync: %v", err)
	}

	deadline := time.Now().Add(3 * time.Second)
	for time.Now().Before(deadline) {
		if h.events.CountOf(ws.EventSyncEnded) == 1 {
			return
		}
		time.Sleep(20 * time.Millisecond)
	}
	t.Fatalf("SYNC_ENDED was never broadcast, saw %v", h.events.TypesPublished())
}
